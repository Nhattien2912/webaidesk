// AI Desk release records: the ONE reviewed source of release metadata for both the website
// download (/api/releases/latest, /api/download/*) and the desktop update feed (/api/updates/*).
//
// Data lives in server/releases.json and is changed only by scripts/release.mjs (stage / approve /
// publish / withdraw) plus code review. It is bundled into the Pages Functions at build time, so a
// publication becomes visible to the website AND the updater in the same deploy (atomic).
//
// A record is servable only when it passes validateRecord() and is published + approved + signed.
// Anything malformed, duplicated or incomplete is excluded (fail closed).

export const RELEASE_CHANNELS = ['stable'] as const
export type ReleaseChannel = (typeof RELEASE_CHANNELS)[number]
export const DEFAULT_CHANNEL: ReleaseChannel = 'stable'
export const UPDATE_METADATA_FILE = 'latest.yml'
export const MAX_METADATA_BYTES = 64 * 1024

export type RecordStatus = 'staged' | 'published' | 'withdrawn'

export interface ArtifactRef {
  fileName: string
  /** Immutable key: releases/<channel>/<version>/<fileName>. */
  r2Key: string
  sizeBytes: number
  /** Lower-case hex SHA-256 of the exact bytes in R2 (also stored as R2 metadata `sha256`). */
  sha256: string
}

export interface InstallerArtifact extends ArtifactRef {
  /** Base64 SHA-512 exactly as written by electron-builder in latest.yml. */
  sha512: string
  /** `<installer>.blockmap` generated by electron-builder for the same build. */
  blockmap: ArtifactRef
}

export interface ReleaseRecord {
  version: string
  channel: ReleaseChannel
  /** ISO date-time (electron-builder releaseDate). */
  releasedAt: string
  minOs: string
  commit?: string
  notesUrl?: string
  signature: 'signed' | 'unsigned'
  signer?: string
  status: RecordStatus
  approved: boolean
  artifacts: {
    /** NSIS installer: website download + update feed. */
    installer: InstallerArtifact
    /** electron-builder latest.yml for this build, served verbatim by the update feed. */
    updateMetadata: ArtifactRef
    /** Portable exe: website download only, never offered by the updater. */
    portable?: ArtifactRef
  }
}

export interface ReleaseFile {
  schemaVersion: 1
  releases: ReleaseRecord[]
}

const SEMVER = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$/
const SHA256 = /^[a-f0-9]{64}$/
const SHA512_B64 = /^[A-Za-z0-9+/]{86}==$/
export const EXE_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]{0,150}\.exe$/

export function compareSemver(a: string, b: string): number {
  const ma = SEMVER.exec(a)
  const mb = SEMVER.exec(b)
  if (!ma || !mb) return 0
  for (let i = 1; i <= 3; i++) {
    const d = Number(ma[i]) - Number(mb[i])
    if (d !== 0) return d
  }
  if (!ma[4] && !mb[4]) return 0
  if (!ma[4]) return 1
  if (!mb[4]) return -1
  const pa = ma[4].split('.')
  const pb = mb[4].split('.')
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    if (pa[i] === undefined) return -1
    if (pb[i] === undefined) return 1
    const na = /^\d+$/.test(pa[i])
    const nb = /^\d+$/.test(pb[i])
    if (na && nb && Number(pa[i]) !== Number(pb[i])) return Number(pa[i]) - Number(pb[i])
    if (na !== nb) return na ? -1 : 1
    if (pa[i] !== pb[i]) return pa[i] < pb[i] ? -1 : 1
  }
  return 0
}

export function immutableKey(channel: string, version: string, fileName: string): string {
  return `releases/${channel}/${version}/${fileName}`
}

function isRecordObj(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v)
}

function checkArtifact(raw: unknown, channel: string, version: string, label: string, name: RegExp | string): string[] {
  if (!isRecordObj(raw)) return [`${label} missing`]
  const errors: string[] = []
  const { fileName, r2Key, sizeBytes, sha256 } = raw
  if (typeof fileName !== 'string' || (typeof name === 'string' ? fileName !== name : !name.test(fileName))) errors.push(`${label}.fileName invalid`)
  if (typeof fileName === 'string' && r2Key !== immutableKey(channel, version, fileName)) errors.push(`${label}.r2Key must be ${immutableKey(channel, version, String(fileName))}`)
  if (typeof sizeBytes !== 'number' || !Number.isInteger(sizeBytes) || sizeBytes <= 0) errors.push(`${label}.sizeBytes invalid`)
  if (typeof sha256 !== 'string' || !SHA256.test(sha256)) errors.push(`${label}.sha256 invalid`)
  return errors
}

/** Structural validation of one record. Returns a list of problems (empty = valid). */
export function validateRecord(raw: unknown): string[] {
  if (!isRecordObj(raw)) return ['record is not an object']
  const errors: string[] = []
  const { version, channel, releasedAt, minOs, status, approved, signature, artifacts, commit, notesUrl } = raw
  if (typeof version !== 'string' || !SEMVER.test(version)) errors.push('version is not semver')
  if (typeof channel !== 'string' || !(RELEASE_CHANNELS as readonly string[]).includes(channel)) errors.push('unknown channel')
  if (typeof releasedAt !== 'string' || Number.isNaN(Date.parse(releasedAt))) errors.push('releasedAt invalid')
  if (typeof minOs !== 'string' || !minOs.trim()) errors.push('minOs missing')
  if (status !== 'staged' && status !== 'published' && status !== 'withdrawn') errors.push('status invalid')
  if (typeof approved !== 'boolean') errors.push('approved must be boolean')
  if (signature !== 'signed' && signature !== 'unsigned') errors.push('signature invalid')
  if (status === 'published' && approved !== true) errors.push('published without approval')
  if (commit !== undefined && (typeof commit !== 'string' || !/^[a-f0-9]{7,40}$/.test(commit))) errors.push('commit invalid')
  if (notesUrl !== undefined && (typeof notesUrl !== 'string' || !notesUrl.startsWith('https://'))) errors.push('notesUrl must be https')
  if (!isRecordObj(artifacts)) return [...errors, 'artifacts missing']
  if (errors.length) return errors
  const v = version as string
  const ch = channel as string
  const inst = artifacts.installer
  errors.push(...checkArtifact(inst, ch, v, 'installer', EXE_NAME))
  if (isRecordObj(inst)) {
    if (typeof inst.sha512 !== 'string' || !SHA512_B64.test(inst.sha512)) errors.push('installer.sha512 invalid')
    errors.push(...checkArtifact(inst.blockmap, ch, v, 'installer.blockmap', `${String(inst.fileName)}.blockmap`))
  }
  errors.push(...checkArtifact(artifacts.updateMetadata, ch, v, 'updateMetadata', UPDATE_METADATA_FILE))
  if (isRecordObj(artifacts.updateMetadata) && typeof artifacts.updateMetadata.sizeBytes === 'number' && artifacts.updateMetadata.sizeBytes > MAX_METADATA_BYTES) {
    errors.push('updateMetadata too large')
  }
  if (artifacts.portable !== undefined) errors.push(...checkArtifact(artifacts.portable, ch, v, 'portable', EXE_NAME))
  return errors
}

export interface CatalogCheck {
  /** Records that are structurally valid and not involved in a conflict. */
  valid: ReleaseRecord[]
  errors: string[]
}

/** Validates every record and drops duplicates (same channel+version, file name or R2 key). */
export function checkCatalog(file: unknown): CatalogCheck {
  if (!isRecordObj(file) || file.schemaVersion !== 1 || !Array.isArray(file.releases)) {
    return { valid: [], errors: ['release file must be {schemaVersion: 1, releases: []}'] }
  }
  const errors: string[] = []
  const ok: ReleaseRecord[] = []
  file.releases.forEach((r, i) => {
    const e = validateRecord(r)
    if (e.length) errors.push(...e.map((m) => `releases[${i}]: ${m}`))
    else ok.push(r as ReleaseRecord)
  })
  const count = new Map<string, number>()
  const bump = (k: string) => count.set(k, (count.get(k) ?? 0) + 1)
  const keysOf = (r: ReleaseRecord) => {
    const a = r.artifacts
    const files = [a.installer, a.installer.blockmap, a.updateMetadata, ...(a.portable ? [a.portable] : [])]
    return [`version:${r.channel}/${r.version}`, ...files.map((f) => `key:${f.r2Key}`), ...[a.installer, ...(a.portable ? [a.portable] : [])].map((f) => `file:${f.fileName}`)]
  }
  ok.forEach((r) => keysOf(r).forEach(bump))
  const valid = ok.filter((r) => {
    const dup = keysOf(r).filter((k) => (count.get(k) ?? 0) > 1)
    if (dup.length) errors.push(`${r.channel}/${r.version}: duplicate ${dup.join(', ')}`)
    return dup.length === 0
  })
  return { valid, errors }
}

export interface ServePolicy {
  /** Website download only: mirror of ALLOW_UNSIGNED_DOWNLOAD. The update feed never serves unsigned builds. */
  allowUnsigned?: boolean
}

export function isServable(r: ReleaseRecord, policy: ServePolicy = {}): boolean {
  return r.status === 'published' && r.approved === true && (r.signature === 'signed' || policy.allowUnsigned === true)
}

/** The current release of a channel: highest semver among servable records. Website and updater share it. */
export function currentRelease(records: readonly ReleaseRecord[], channel: string, policy: ServePolicy = {}): ReleaseRecord | null {
  const candidates = records.filter((r) => r.channel === channel && isServable(r, policy))
  candidates.sort((a, b) => compareSemver(b.version, a.version))
  return candidates[0] ?? null
}
